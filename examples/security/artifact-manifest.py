#!/usr/bin/env python3
"""artifact-manifest.py: keep a committed, generated artifact provably in step with its source.

What it is for: when a generated file is committed (a minified bundle, a compiled schema, a
parser table, a vendored build output), two things go wrong. Someone edits the source and
forgets to regenerate, so the next release ships old behaviour. Or someone edits the generated
file by hand, and the next regeneration silently erases the edit (or worse, the hand edit is a
backdoor nobody reviews as code). A manifest of sha256 sums, written only by `build`, makes
both visible: any one-sided edit is red. When the generator is deterministic, `check` also
rebuilds from the source and compares bytes, which catches a hand edit that also rewrote the
manifest. No network, Python 3 standard library only.

The manifest (text, committed next to the outputs):

    # Generated by artifact-manifest.py build -- do not edit by hand.
    tool upcase-1
    src <sha256>  greeting.txt
    out <sha256>  greeting.out

Subcommands (the same flags for both):
  build   run the build command for every source, write the outputs, write the manifest.
  check   verify the manifest. Red on: a source with no manifest entry or a changed hash; an
          output that is missing, has no source (an orphan), has no entry or a changed hash; a
          manifest entry for a file that no longer exists; and, when the build command is given
          and the tool version equals the recorded one, a rebuild whose bytes differ from the
          committed output. A different tool version skips the rebuild half and says so (a
          different minifier may emit different bytes), the sha256 half still holds.

Flags: --root DIR  --manifest FILE  --src-dir DIR  --out-dir DIR  --src-ext .txt  --out-ext .out
       --build-cmd 'CMD'          run with sh -c in --root; reads $SRC, writes $OUT (paths)
       --tool-version-cmd 'CMD'   prints the generator's version; recorded as `tool ...`
All paths are relative to --root. `--self-test` builds fixtures in a temp dir and requires every
mutation to turn red.

Exit status: 0 clean, 1 drift, 2 usage or unreadable input.
"""

import argparse
import contextlib
import hashlib
import io
import os
import shutil
import subprocess
import sys
import tempfile


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def list_files(directory, ext):
    if not os.path.isdir(directory):
        return []
    return sorted(f for f in os.listdir(directory) if f.endswith(ext) and os.path.isfile(os.path.join(directory, f)))


def stem(name, ext):
    return name[: -len(ext)]


def run_cmd(cmd, cwd, env_extra=None):
    env = dict(os.environ)
    env.update(env_extra or {})
    return subprocess.run(["sh", "-c", cmd], cwd=cwd, env=env, capture_output=True, text=True)


def tool_version(a):
    if not a.tool_version_cmd:
        return ""
    r = run_cmd(a.tool_version_cmd, a.root)
    return r.stdout.strip() if r.returncode == 0 else "unknown"


def build_one(a, src_name, out_path):
    r = run_cmd(a.build_cmd, a.root, {"SRC": os.path.join(a.src_dir, src_name), "OUT": out_path})
    if r.returncode != 0:
        raise RuntimeError(f"build command failed for {src_name}: {r.stderr.strip() or r.stdout.strip()}")


def cmd_build(a):
    if not a.build_cmd:
        print("artifact-manifest: build needs --build-cmd", file=sys.stderr)
        return 2
    src_abs, out_abs = os.path.join(a.root, a.src_dir), os.path.join(a.root, a.out_dir)
    sources = list_files(src_abs, a.src_ext)
    if not sources:
        print(f"artifact-manifest: no {a.src_ext} sources in {a.src_dir}", file=sys.stderr)
        return 2
    os.makedirs(out_abs, exist_ok=True)
    lines = ["# Generated by artifact-manifest.py build -- do not edit by hand.",
             "# Verified by artifact-manifest.py check: sha256 of every source and output, and a rebuild comparison."]
    if a.tool_version_cmd:
        lines.append(f"tool {tool_version(a)}")
    try:
        for s in sources:
            o = stem(s, a.src_ext) + a.out_ext
            build_one(a, s, os.path.join(a.out_dir, o))
            lines.append(f"src {sha256(os.path.join(src_abs, s))}  {s}")
            lines.append(f"out {sha256(os.path.join(out_abs, o))}  {o}")
            print(f"artifact-manifest: {a.src_dir}/{s} -> {a.out_dir}/{o}")
    except RuntimeError as err:
        print(f"artifact-manifest: {err}", file=sys.stderr)
        return 1
    mpath = os.path.join(a.root, a.manifest)
    with open(mpath + ".tmp", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    os.replace(mpath + ".tmp", mpath)
    print(f"artifact-manifest: wrote {a.manifest}")
    return 0


def parse_manifest(path):
    tool, src, out = None, {}, {}
    for line in open(path, encoding="utf-8").read().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        kind, _, rest = line.partition(" ")
        if kind == "tool":
            tool = rest.strip()
        elif kind in ("src", "out"):
            digest, _, name = rest.partition("  ")
            (src if kind == "src" else out)[name.strip()] = digest.strip()
    return tool, src, out


def check_manifest(a):
    """Return (problems, rebuild_note)."""
    mpath = os.path.join(a.root, a.manifest)
    if not os.path.isfile(mpath):
        return [f"{a.manifest} is missing; run `build`"], "not run"
    problems = []
    recorded_tool, want_src, want_out = parse_manifest(mpath)
    src_abs, out_abs = os.path.join(a.root, a.src_dir), os.path.join(a.root, a.out_dir)
    sources, outputs = list_files(src_abs, a.src_ext), list_files(out_abs, a.out_ext)
    for s in sources:
        if s not in want_src:
            problems.append(f"{a.src_dir}/{s} is not in {a.manifest}; run `build` and commit the output and the manifest")
        elif sha256(os.path.join(src_abs, s)) != want_src[s]:
            problems.append(f"{a.src_dir}/{s} changed since {a.manifest} was written; run `build` and commit the output and the manifest")
        if stem(s, a.src_ext) + a.out_ext not in outputs:
            problems.append(f"{a.out_dir}/{stem(s, a.src_ext) + a.out_ext} (built from {s}) is missing; run `build`")
    src_stems = {stem(s, a.src_ext) for s in sources}
    for o in outputs:
        if stem(o, a.out_ext) not in src_stems:
            problems.append(f"{a.out_dir}/{o} has no source {a.src_dir}/{stem(o, a.out_ext) + a.src_ext} (a generated file must come from one)")
        elif o not in want_out:
            problems.append(f"{a.out_dir}/{o} is not in {a.manifest}; run `build`")
        elif sha256(os.path.join(out_abs, o)) != want_out[o]:
            problems.append(f"{a.out_dir}/{o} does not match {a.manifest}: it was edited by hand or rebuilt without writing the "
                            f"manifest; edit {a.src_dir}/{stem(o, a.out_ext) + a.src_ext} and run `build`")
    for s in want_src:
        if s not in sources:
            problems.append(f"{a.manifest} lists {a.src_dir}/{s}, which no longer exists")
    for o in want_out:
        if o not in outputs:
            problems.append(f"{a.manifest} lists {a.out_dir}/{o}, which no longer exists")
    note = "skipped (no --build-cmd)"
    if a.build_cmd:
        have = tool_version(a)
        if a.tool_version_cmd and recorded_tool is not None and have != recorded_tool:
            note = f"skipped (tool {have!r}, manifest recorded {recorded_tool!r})"
        else:
            note = "ok"
            tmp = tempfile.mkdtemp(prefix="artifact-rebuild-")
            try:
                for s in sources:
                    o = stem(s, a.src_ext) + a.out_ext
                    committed = os.path.join(out_abs, o)
                    if not os.path.isfile(committed):
                        continue
                    try:
                        build_one(a, s, os.path.join(tmp, o))
                    except RuntimeError as err:
                        problems.append(str(err))
                        note = "FAILED"
                        continue
                    if sha256(os.path.join(tmp, o)) != sha256(committed):
                        problems.append(f"rebuilding {a.src_dir}/{s} gives different bytes than the committed {a.out_dir}/{o}; "
                                        f"run `build` (or the committed file was edited and the manifest rewritten to match)")
                        note = "FAILED"
            finally:
                shutil.rmtree(tmp, ignore_errors=True)
    return problems, note


def cmd_check(a):
    problems, note = check_manifest(a)
    if problems:
        print("artifact-manifest: FAIL", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1
    n = len(list_files(os.path.join(a.root, a.src_dir), a.src_ext))
    print(f"artifact-manifest: OK -- {n} source(s) match their committed outputs and {a.manifest} (rebuild comparison: {note})")
    return 0


# ---- self-test ----------------------------------------------------------------------------------

def self_test():
    cases, bad = 0, 0

    def fixture():
        tmp = tempfile.mkdtemp(prefix="artifact-selftest-")
        os.makedirs(os.path.join(tmp, "src"))
        for n, t in (("a.txt", "alpha\n"), ("b.txt", "beta\n")):
            open(os.path.join(tmp, "src", n), "w").write(t)
        a = argparse.Namespace(root=tmp, manifest="m.manifest", src_dir="src", out_dir="out", src_ext=".txt", out_ext=".out",
                               build_cmd='tr a-z A-Z < "$SRC" > "$OUT"', tool_version_cmd="echo upcase-1")
        with contextlib.redirect_stdout(io.StringIO()):
            assert cmd_build(a) == 0
        return tmp, a

    def case(name, want, mutate, version_cmd=None):
        nonlocal cases, bad
        cases += 1
        tmp, a = fixture()
        try:
            mutate(tmp)
            if version_cmd:
                a.tool_version_cmd = version_cmd
            problems, note = check_manifest(a)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        ok = (not problems) if want is None else any(want in p for p in problems)
        if want is None and ok and version_cmd:
            ok = note.startswith("skipped")
        print(f"  self-test {'ok  ' if ok else 'FAIL'} {name}" + ("" if ok else f" -- got {problems[:2]} / {note}"))
        bad += 0 if ok else 1

    p = lambda tmp, *parts: os.path.join(tmp, *parts)
    case("untouched build is green (hash and rebuild halves)", None, lambda t: None)
    case("a source is edited without a rebuild", "changed since",
         lambda t: open(p(t, "src", "a.txt"), "a").write("more\n"))
    case("an output is edited by hand", "does not match",
         lambda t: open(p(t, "out", "a.out"), "a").write("hand edit\n"))
    case("a new source has no manifest entry", "is not in",
         lambda t: open(p(t, "src", "c.txt"), "w").write("gamma\n"))
    case("an output has no source (orphan)", "has no source",
         lambda t: open(p(t, "out", "z.out"), "w").write("orphan\n"))
    case("an output is deleted", "is missing", lambda t: os.remove(p(t, "out", "a.out")))
    case("a source is deleted but still listed", "no longer exists",
         lambda t: (os.remove(p(t, "src", "b.txt")), os.remove(p(t, "out", "b.out"))))
    case("the manifest is missing", "is missing", lambda t: os.remove(p(t, "m.manifest")))

    def edit_and_rewrite_manifest(t):
        path = p(t, "out", "a.out")
        old = sha256(path)
        open(path, "a").write("backdoor\n")
        m = open(p(t, "m.manifest")).read().replace(old, sha256(path))
        open(p(t, "m.manifest"), "w").write(m)
    case("an output is edited and the manifest hash rewritten to match (only the rebuild sees it)", "rebuilding",
         edit_and_rewrite_manifest)
    case("a different tool version skips the rebuild half, the hash half still holds", None,
         edit_and_rewrite_manifest, version_cmd="echo upcase-2")
    if bad:
        print(f"artifact-manifest: self-test FAIL ({bad} of {cases} cases wrong)", file=sys.stderr)
        return 1
    print(f"artifact-manifest: self-test OK ({cases} cases)")
    return 0


def main():
    ap = argparse.ArgumentParser(description="Keep a committed generated artifact in step with its source.")
    ap.add_argument("command", nargs="?", choices=["build", "check"])
    ap.add_argument("--root", default=".")
    ap.add_argument("--manifest", default="artifacts.manifest")
    ap.add_argument("--src-dir", default="src")
    ap.add_argument("--out-dir", default="out")
    ap.add_argument("--src-ext", default=".txt")
    ap.add_argument("--out-ext", default=".out")
    ap.add_argument("--build-cmd", default="")
    ap.add_argument("--tool-version-cmd", default="")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    if not a.command:
        ap.print_usage(sys.stderr)
        return 2
    a.root = os.path.abspath(a.root)
    return cmd_build(a) if a.command == "build" else cmd_check(a)


if __name__ == "__main__":
    sys.exit(main())
